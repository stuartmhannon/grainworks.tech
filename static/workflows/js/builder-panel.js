/* ── Export YAML ──────────────────────────── */

/**
 * Serialize a workflow definition object to YAML using string construction.
 * Produces valid YAML with no external dependencies.
 *
 * @param {object} workflow - Workflow object with agent_name, agent_id, version,
 *                            description, specialists array.
 * @returns {string} YAML-formatted string
 */
export function exportYaml(workflow) {
  const lines = [];
  const indent = '  ';

  // Header
  lines.push('# grainworks workflow definition');
  lines.push('# generated by workbench builder');
  lines.push('');

  // Agent name (identifier, no quotes needed for simple strings)
  lines.push('agent_name: ' + String(workflow.agent_name || ''));

  // Agent ID
  lines.push('agent_id: ' + String(workflow.agent_id || ''));

  // Version
  lines.push('version: ' + String(workflow.version || ''));

  // Description (multi-line safe if it contains newlines)
  const desc = String(workflow.description || '');
  if (desc.includes('\n')) {
    lines.push('description: |');
    desc.split('\n').forEach(line => {
      lines.push(indent + line);
    });
  } else {
    lines.push('description: ' + desc);
  }

  // Specialists array
  lines.push('specialists:');
  if (workflow.specialists && Array.isArray(workflow.specialists) && workflow.specialists.length > 0) {
    workflow.specialists.forEach((sp, idx) => {
      lines.push(indent + '- agent_id: ' + String(sp.agent_id || ''));
      lines.push(indent + '  name: ' + String(sp.name || ''));
      lines.push(indent + '  code: ' + String(sp.code || ''));
      if (sp.priority !== undefined && sp.priority !== null) {
        lines.push(indent + '  priority: ' + Number(sp.priority));
      }
      if (sp.keywords && Array.isArray(sp.keywords) && sp.keywords.length > 0) {
        lines.push(indent + '  keywords:');
        sp.keywords.forEach(kw => {
          lines.push(indent + indent + '- ' + String(kw));
        });
      }
      if (sp.aliases && Array.isArray(sp.aliases) && sp.aliases.length > 0) {
        lines.push(indent + '  aliases:');
        sp.aliases.forEach(al => {
          lines.push(indent + indent + '- ' + String(al));
        });
      }
      // Separator between specialists
      if (idx < workflow.specialists.length - 1) {
        lines.push('');
      }
    });
  } else {
    lines.push(indent + '[]');
  }

  return lines.join('\n');
}

/* ── API fetching ─────────────────────────── */

/**
 * Fetch workflows from the API endpoint.
 * @returns {Promise<Array>} Array of workflow objects, or null on error.
 */
async function fetchWorkflows() {
  try {
    const resp = await fetch('/api/workflows?_=' + Date.now());
    if (!resp.ok) throw new Error('HTTP ' + resp.status);
    const data = await resp.json();
    return (data && data.workflows) || [];
  } catch {
    return null;
  }
}

/* ── Modal for YAML output ───────────────── */

function showYamlModal(yamlContent, workflowName) {
  const overlay = document.createElement('div');
  overlay.className = 'bld-modal-overlay';

  const modal = document.createElement('div');
  modal.className = 'bld-modal';

  // Header
  const header = document.createElement('div');
  header.className = 'bld-modal-header';

  const title = document.createElement('div');
  title.className = 'bld-modal-title';
  title.textContent = 'YAML — ' + (workflowName || 'workflow');
  header.appendChild(title);

  const closeBtn = document.createElement('button');
  closeBtn.className = 'bld-modal-close';
  closeBtn.innerHTML = '&times;';
  closeBtn.setAttribute('aria-label', 'Close');
  closeBtn.addEventListener('click', () => overlay.remove());
  header.appendChild(closeBtn);

  modal.appendChild(header);

  // Copy button
  const toolbar = document.createElement('div');
  toolbar.className = 'bld-modal-toolbar';

  const copyBtn = document.createElement('button');
  copyBtn.className = 'bld-modal-btn';
  copyBtn.textContent = '📋 Copy';
  copyBtn.addEventListener('click', async () => {
    try {
      await navigator.clipboard.writeText(yamlContent);
      copyBtn.textContent = '✅ Copied!';
      setTimeout(() => { copyBtn.textContent = '📋 Copy'; }, 2000);
    } catch {
      copyBtn.textContent = '❌ Failed';
      setTimeout(() => { copyBtn.textContent = '📋 Copy'; }, 2000);
    }
  });
  toolbar.appendChild(copyBtn);

  modal.appendChild(toolbar);

  // YAML content
  const pre = document.createElement('pre');
  pre.className = 'bld-modal-code';
  pre.textContent = yamlContent;
  modal.appendChild(pre);

  // Download button
  const footer = document.createElement('div');
  footer.className = 'bld-modal-footer';

  const downloadBtn = document.createElement('button');
  downloadBtn.className = 'bld-modal-btn';
  downloadBtn.textContent = '⬇ Download .yaml';
  downloadBtn.addEventListener('click', () => {
    const blob = new Blob([yamlContent], { type: 'text/yaml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = (workflowName || 'workflow').replace(/[^a-zA-Z0-9_-]/g, '_') + '.yaml';
    a.click();
    URL.revokeObjectURL(url);
  });
  footer.appendChild(downloadBtn);

  modal.appendChild(footer);

  overlay.appendChild(modal);

  // Close on backdrop click
  overlay.addEventListener('click', (e) => {
    if (e.target === overlay) overlay.remove();
  });

  // Close on Escape
  const keyHandler = (e) => {
    if (e.key === 'Escape') {
      overlay.remove();
      document.removeEventListener('keydown', keyHandler);
    }
  };
  document.addEventListener('keydown', keyHandler);

  document.body.appendChild(overlay);
}

/* ── Save workflow to API ─────────────────── */

/**
 * Save workflow changes via PUT to /api/workflows/:agent_id.
 * @param {object} workflow - Workflow object with agent_id, agent_name, description, version
 * @returns {Promise<object|null>} Updated workflow object or null on failure
 */
async function saveWorkflow(workflow) {
  try {
    const body = {
      agent_name: workflow.agent_name || '',
      description: workflow.description || '',
      version: workflow.version || '',
    };
    const resp = await fetch('/api/workflows/' + encodeURIComponent(workflow.agent_id), {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    });
    if (!resp.ok) {
      if (resp.status === 404) {
        return { error: 'API endpoint not found (PUT /api/workflows/' + encodeURIComponent(workflow.agent_id) + ') — workflow-store backend may not be built.' };
      }
      throw new Error('HTTP ' + resp.status);
    }
    const data = await resp.json();
    return data || null;
  } catch (err) {
    return { error: 'Save failed: ' + err.message };
  }
}

/* ── Build detail panel ──────────────────── */

function buildDetailPanel(workflow) {
  const panel = document.createElement('div');
  panel.className = 'bld-detail';

  // Back button
  const backBtn = document.createElement('button');
  backBtn.className = 'bld-detail-back';
  backBtn.textContent = '← Back to list';
  backBtn.addEventListener('click', () => {
    detailOpen = null;
    const container = document.getElementById('builder-container');
    if (container) renderBuilder(container);
  });
  panel.appendChild(backBtn);

  // ── Editable header ──────────────────────────
  const header = document.createElement('div');
  header.className = 'bld-detail-header';

  const nameInput = document.createElement('input');
  nameInput.type = 'text';
  nameInput.className = 'bld-edit-input bld-edit-name';
  nameInput.value = workflow.agent_name || 'Unnamed';
  nameInput.readOnly = true;
  nameInput.disabled = false;
  header.appendChild(nameInput);

  panel.appendChild(header);

  // ── Meta grid ────────────────────────────────
  const meta = document.createElement('div');
  meta.className = 'bld-detail-meta';

  const metaItems = [
    { label: 'agent_id', value: workflow.agent_id || '—' },
    { label: 'version', value: workflow.version || '—' },
  ];
  if (workflow.last_modified) {
    metaItems.push({ label: 'last modified', value: new Date(workflow.last_modified).toLocaleString() });
  }

  metaItems.forEach(item => {
    const el = document.createElement('span');
    el.className = 'bld-meta-item';
    el.innerHTML = '<span class="bld-meta-label">' + item.label + '</span><span class="bld-meta-val">' + escapeHtml(item.value) + '</span>';
    meta.appendChild(el);
  });

  panel.appendChild(meta);

  // ── Editable description ──────────────────────
  const descSection = document.createElement('div');
  descSection.className = 'bld-detail-section';

  const descLabel = document.createElement('div');
  descLabel.className = 'bld-section-title';
  descLabel.textContent = 'description';
  descSection.appendChild(descLabel);

  const descTextarea = document.createElement('textarea');
  descTextarea.className = 'bld-edit-input bld-edit-textarea';
  descTextarea.rows = 3;
  descTextarea.value = workflow.description || '';
  descTextarea.readOnly = true;
  descSection.appendChild(descTextarea);

  panel.appendChild(descSection);

  // File path
  if (workflow.file_path) {
    const fp = document.createElement('div');
    fp.className = 'bld-detail-section';
    fp.innerHTML = '<div class="bld-section-title">file path</div><div class="bld-section-text bld-section-mono">' + escapeHtml(workflow.file_path) + '</div>';
    panel.appendChild(fp);
  }

  // Specialists count + list
  const specialists = workflow.specialists || [];
  const spSection = document.createElement('div');
  spSection.className = 'bld-detail-section';
  spSection.innerHTML = '<div class="bld-section-title">specialists (' + specialists.length + ')</div>';

  if (specialists.length === 0) {
    const empty = document.createElement('div');
    empty.className = 'bld-section-text bld-dim';
    empty.textContent = 'No specialists defined.';
    spSection.appendChild(empty);
  } else {
    const list = document.createElement('div');
    list.className = 'bld-sp-list';
    specialists.forEach(sp => {
      const card = document.createElement('div');
      card.className = 'bld-sp-card';

      const nameLine = document.createElement('div');
      nameLine.className = 'bld-sp-name';
      nameLine.textContent = (sp.name || sp.agent_id || '?') + ' (' + (sp.code || '—') + ')';
      card.appendChild(nameLine);

      const metaLine = document.createElement('div');
      metaLine.className = 'bld-sp-meta';
      metaLine.textContent = 'agent_id: ' + (sp.agent_id || '—') + ' | priority: ' + (sp.priority !== undefined ? sp.priority : '—');
      card.appendChild(metaLine);

      if (sp.keywords && sp.keywords.length > 0) {
        const kwLine = document.createElement('div');
        kwLine.className = 'bld-sp-keywords';
        kwLine.textContent = sp.keywords.join(', ');
        card.appendChild(kwLine);
      }

      list.appendChild(card);
    });
    spSection.appendChild(list);
  }

  panel.appendChild(spSection);

  // ── Action row: Edit / Save / Cancel / Export ──
  const actionSection = document.createElement('div');
  actionSection.className = 'bld-action-row';

  const editBtn = document.createElement('button');
  editBtn.className = 'bld-edit-btn';
  editBtn.textContent = '✏ Edit';
  actionSection.appendChild(editBtn);

  const saveBtn = document.createElement('button');
  saveBtn.className = 'bld-save-btn';
  saveBtn.textContent = '💾 Save';
  saveBtn.style.display = 'none';
  actionSection.appendChild(saveBtn);

  const cancelBtn = document.createElement('button');
  cancelBtn.className = 'bld-cancel-btn';
  cancelBtn.textContent = 'Cancel';
  cancelBtn.style.display = 'none';
  actionSection.appendChild(cancelBtn);

  const exportBtn = document.createElement('button');
  exportBtn.className = 'bld-export-btn';
  exportBtn.textContent = '✎ Export YAML';
  exportBtn.addEventListener('click', () => {
    const yaml = exportYaml(workflow);
    showYamlModal(yaml, workflow.agent_name);
  });
  actionSection.appendChild(exportBtn);

  // Feedback area
  const feedback = document.createElement('div');
  feedback.className = 'bld-feedback';
  feedback.style.display = 'none';
  actionSection.appendChild(feedback);

  panel.appendChild(actionSection);

  // ── Edit / Save / Cancel logic ─────────────────
  let isEditing = false;
  let originalName = nameInput.value;
  let originalDesc = descTextarea.value;

  function enterEditMode() {
    isEditing = true;
    originalName = nameInput.value;
    originalDesc = descTextarea.value;
    nameInput.readOnly = false;
    nameInput.classList.add('bld-editing');
    descTextarea.readOnly = false;
    descTextarea.classList.add('bld-editing');
    editBtn.style.display = 'none';
    saveBtn.style.display = '';
    cancelBtn.style.display = '';
    feedback.style.display = 'none';
    nameInput.focus();
  }

  function cancelEdit() {
    isEditing = false;
    nameInput.value = originalName;
    descTextarea.value = originalDesc;
    nameInput.readOnly = true;
    nameInput.classList.remove('bld-editing');
    descTextarea.readOnly = true;
    descTextarea.classList.remove('bld-editing');
    editBtn.style.display = '';
    saveBtn.style.display = 'none';
    cancelBtn.style.display = 'none';
    feedback.style.display = 'none';
  }

  async function doSave() {
    // Build a temp workflow object with the current edits
    const updated = {
      agent_id: workflow.agent_id,
      agent_name: nameInput.value.trim(),
      description: descTextarea.value.trim(),
      version: workflow.version || '',
    };

    // Disable controls and show saving state
    saveBtn.disabled = true;
    cancelBtn.disabled = true;
    nameInput.readOnly = true;
    descTextarea.readOnly = true;
    saveBtn.textContent = '⏳ Saving…';
    feedback.className = 'bld-feedback bld-feedback-info';
    feedback.textContent = 'Saving…';
    feedback.style.display = '';

    const result = await saveWorkflow(updated);

    saveBtn.disabled = false;
    cancelBtn.disabled = false;
    saveBtn.textContent = '💾 Save';

    if (result === null) {
      // No body returned — treat as success (maybe API returns 204)
      feedback.className = 'bld-feedback bld-feedback-ok';
      feedback.textContent = '✅ Saved successfully.';
      feedback.style.display = '';
      // Update local workflow state
      workflow.agent_name = updated.agent_name;
      workflow.description = updated.description;
      originalName = nameInput.value;
      originalDesc = descTextarea.value;
      // Refresh cached data
      refreshWorkflowCache(workflow);
      // Exit edit mode cleanly
      isEditing = false;
      nameInput.readOnly = true;
      nameInput.classList.remove('bld-editing');
      descTextarea.readOnly = true;
      descTextarea.classList.remove('bld-editing');
      editBtn.style.display = '';
      saveBtn.style.display = 'none';
      cancelBtn.style.display = 'none';
      setTimeout(() => { feedback.style.display = 'none'; }, 3000);
      return;
    }

    if (result && result.error) {
      // API unavailable or error
      feedback.className = 'bld-feedback bld-feedback-err';
      feedback.textContent = '⚠ ' + result.error;
      feedback.style.display = '';
      // Re-enable editing so user can retry
      nameInput.readOnly = false;
      nameInput.classList.add('bld-editing');
      descTextarea.readOnly = false;
      descTextarea.classList.add('bld-editing');
      return;
    }

    // Success — merge updated data
    feedback.className = 'bld-feedback bld-feedback-ok';
    feedback.textContent = '✅ Saved successfully.';
    feedback.style.display = '';
    workflow.agent_name = updated.agent_name;
    workflow.description = updated.description;
    originalName = nameInput.value;
    originalDesc = descTextarea.value;
    refreshWorkflowCache(workflow);
    // Exit edit mode
    isEditing = false;
    nameInput.readOnly = true;
    nameInput.classList.remove('bld-editing');
    descTextarea.readOnly = true;
    descTextarea.classList.remove('bld-editing');
    editBtn.style.display = '';
    saveBtn.style.display = 'none';
    cancelBtn.style.display = 'none';
    setTimeout(() => { feedback.style.display = 'none'; }, 3000);
  }

  editBtn.addEventListener('click', enterEditMode);
  cancelBtn.addEventListener('click', cancelEdit);
  saveBtn.addEventListener('click', doSave);

  // Enter key in name input triggers save (if editing)
  nameInput.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && isEditing) {
      e.preventDefault();
      doSave();
    }
  });

  // Escape in either field cancels edit
  function escHandler(e) {
    if (e.key === 'Escape' && isEditing) {
      cancelEdit();
    }
  }
  nameInput.addEventListener('keydown', escHandler);
  descTextarea.addEventListener('keydown', escHandler);

  return panel;
}

/**
 * Update the cached workflow object in memory after a save.
 */
function refreshWorkflowCache(updated) {
  if (!cachedWorkflows || !Array.isArray(cachedWorkflows)) return;
  const idx = cachedWorkflows.findIndex(w => w.agent_id === updated.agent_id);
  if (idx !== -1) {
    cachedWorkflows[idx].agent_name = updated.agent_name;
    cachedWorkflows[idx].description = updated.description;
  }
}

/* ── Build workflow list ─────────────────── */

function buildWorkflowList(workflows) {
  const list = document.createElement('div');
  list.className = 'bld-list';

  if (!workflows || workflows.length === 0) {
    const empty = document.createElement('div');
    empty.className = 'empty-state';
    empty.innerHTML = '<div class="big-icon">✎</div><div style="margin-top: 8px; font-size: 11px; color: var(--fg-dim);">No workflows found.</div>';
    return empty;
  }

  workflows.forEach(wf => {
    const card = document.createElement('div');
    card.className = 'bld-card';
    card.addEventListener('click', () => {
      detailOpen = wf;
      const container = document.getElementById('builder-container');
      if (container) {
        container.innerHTML = '';
        container.appendChild(buildDetailPanel(wf));
      }
    });

    // Header: name + version
    const header = document.createElement('div');
    header.className = 'bld-card-header';

    const name = document.createElement('span');
    name.className = 'bld-card-name';
    name.textContent = wf.agent_name || 'Unnamed';
    header.appendChild(name);

    const version = document.createElement('span');
    version.className = 'bld-card-version';
    version.textContent = 'v' + (wf.version || '?');
    header.appendChild(version);

    card.appendChild(header);

    // Agent ID
    const idLine = document.createElement('div');
    idLine.className = 'bld-card-id';
    idLine.textContent = wf.agent_id || '';
    card.appendChild(idLine);

    // Description
    if (wf.description) {
      const desc = document.createElement('div');
      desc.className = 'bld-card-desc';
      desc.textContent = wf.description;
      card.appendChild(desc);
    }

    // Meta footer
    const footer = document.createElement('div');
    footer.className = 'bld-card-footer';

    const specCount = document.createElement('span');
    specCount.className = 'bld-card-stat';
    const sps = (wf.specialists && Array.isArray(wf.specialists)) ? wf.specialists.length : 0;
    specCount.textContent = sps + ' specialist' + (sps !== 1 ? 's' : '');
    footer.appendChild(specCount);

    if (wf.last_modified) {
      const modified = document.createElement('span');
      modified.className = 'bld-card-stat';
      modified.textContent = new Date(wf.last_modified).toLocaleDateString();
      footer.appendChild(modified);
    }

    card.appendChild(footer);

    // Action row: Export YAML button (stopPropagation so clicking it doesn't open detail)
    const actionRow = document.createElement('div');
    actionRow.className = 'bld-card-actions';

    const exportBtn = document.createElement('button');
    exportBtn.className = 'bld-export-btn bld-export-btn-sm';
    exportBtn.textContent = '✎ Export YAML';
    exportBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const yaml = exportYaml(wf);
      showYamlModal(yaml, wf.agent_name);
    });
    actionRow.appendChild(exportBtn);

    card.appendChild(actionRow);

    list.appendChild(card);
  });

  return list;
}

/* ── Build the full builder UI ───────────── */

function buildBuilder(workflows) {
  const container = document.createElement('div');
  container.className = 'bld-builder';

  // Title bar
  const titleBar = document.createElement('div');
  titleBar.className = 'bld-title-bar';
  titleBar.innerHTML = '<div class="bld-title">Workflow Builder</div>';
  if (workflows && Array.isArray(workflows)) {
    const count = document.createElement('div');
    count.className = 'bld-title-count';
    count.textContent = workflows.length + ' workflow' + (workflows.length !== 1 ? 's' : '');
    titleBar.appendChild(count);
  }
  container.appendChild(titleBar);

  // Workflow list
  container.appendChild(buildWorkflowList(workflows));

  return container;
}

/* ── Entry point ──────────────────────────── */

/**
 * Main render function. Loads workflows from /api/workflows and renders
 * the builder UI into the given container.
 *
 * @param {HTMLElement} container - The DOM element to render into
 */
export async function renderBuilder(container) {
  container.innerHTML = '';

  // Show loading state
  container.innerHTML = '<div class="empty-state" style="padding: 40px;"><div class="big-icon">✎</div>Loading workflows…</div>';

  // Fetch workflows from API
  const workflows = await fetchWorkflows();

  if (workflows === null) {
    // API unavailable
    container.innerHTML = '<div class="empty-state" style="padding: 40px;"><div class="big-icon">⚠</div><div style="margin-top: 8px; font-size: 11px; color: var(--fg-dim);">API unavailable — could not reach /api/workflows.<br>Start the workflow-store backend or check the nginx proxy.</div></div>';
    return;
  }

  cachedWorkflows = workflows;

  // If we have a detail open, try to find the matching workflow in fresh data
  if (detailOpen) {
    const match = workflows.find(w => w.agent_id === detailOpen.agent_id);
    if (match) {
      detailOpen = match;
      container.innerHTML = '';
      container.appendChild(buildDetailPanel(match));
      return;
    }
    // Workflow no longer in list, fall through to list view
    detailOpen = null;
  }

  container.innerHTML = '';
  container.appendChild(buildBuilder(workflows));
}
